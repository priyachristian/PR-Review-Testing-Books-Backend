const toRows = (list, taxType) =>
  list.map(([sectionKey, sectionNo, name, description, oldSectionNo = null, paymentCode = null]) => ({
    sectionKey,
    taxType,
    sectionNo,
    name,
    description,
    oldSectionNo,
    paymentCode,
  }));

const sections = [...toRows(TDS_SECTIONS, 'TDS'), ...toRows(TCS_SECTIONS, 'TCS')];

const migrate = async () => {
  let client;
  try {
    const apply = process.argv.slice(2).includes('--apply');
    const db = await getConnection();
    client = db.client;
    console.log(apply ? 'Mode: APPLYING CHANGES' : 'Mode: dry run — pass --apply to write');
    console.log(`Sections to insert: ${sections.length}`);

    if (!apply) {
      console.log('Nothing was written. Re-run with --apply.');
      return;
    }

    const now = new Date();
    const collection = db.common.collection('incometaxsections');
    const result = await collection.insertMany(sections.map(section => ({ ...section, createdAt: now, updatedAt: now })));
    await collection.createIndex({ sectionKey: 1 }, { unique: true });
    console.log(`Inserted: ${result.insertedCount}`);
  } finally {
    if (client) await client.close();
  }
};

migrate()
  .then(() => process.exit(0))
  .catch(error => {
    console.error(error);
    process.exit(1);
  });
